void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
    if (GPIO_Pin == GPIO_PIN_13)
    {
        static uint32_t last_press = 0;
        uint32_t now = HAL_GetTick();

        if (now - last_press < 200)
            return;

        last_press = now;

        if (game_state == 0)
        {
            __HAL_TIM_SET_COUNTER(&htim2, 0);
            start_time = 0;
            game_state = 1;
        }
        else if (game_state == 1)
        {
            stop_time = __HAL_TIM_GET_COUNTER(&htim2);
            game_state = 2;
        }
    }
}
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == LPUART1)
    {
        if (rx_byte == '\r' || rx_byte == '\n')
        {
            if (rx_index > 0)
            {
                rx_buffer[rx_index] = '\0';

                if (strncmp(rx_buffer, "TARGET ", 7) == 0)
                {
                    float new_target = atof(rx_buffer + 7);

                    if (new_target >= 1.0f && new_target <= 60.0f)
                    {
                        target_time = new_target;

                        char msg[] = "Target updated!\r\n";
                        HAL_UART_Transmit(&hlpuart1,
                                          (uint8_t *)msg,
                                          strlen(msg),
                                          100);
                    }
                }

                rx_index = 0;
            }
        }
        else if (rx_index < sizeof(rx_buffer) - 1)
        {
            rx_buffer[rx_index++] = rx_byte;
        }
        else
        {
            rx_index = 0;
        }

        HAL_UART_Receive_IT(&hlpuart1, &rx_byte, 1);
    }
}
